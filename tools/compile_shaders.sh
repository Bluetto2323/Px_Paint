#!/usr/bin/env bash
# Regenerates app/src/main/cpp/shaders/generated/TriangleShaders.h
#  - Vulkan GLSL 450  -> SPIR-V (embedded as uint32_t arrays)
#  - GLSL ES 3.00     -> validated, embedded as source strings
#
# Usage: tools/compile_shaders.sh [path/to/glslangValidator]
# Any glslangValidator works (Vulkan SDK, NDK has glslc instead: see below).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/app/src/main/cpp/shaders"
OUT="$SRC/generated/TriangleShaders.h"
GLSLANG="${1:-${GLSLANG:-glslangValidator}}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

command -v "$GLSLANG" >/dev/null 2>&1 || [ -x "$GLSLANG" ] || { echo "glslangValidator not found: $GLSLANG" >&2; exit 1; }

# SPIR-V 1.0 so that Vulkan 1.0 drivers accept it.
"$GLSLANG" -V --target-env vulkan1.0 --vn kTriangleVertSpv -o "$TMP/vert.h" "$SRC/triangle.vert"
"$GLSLANG" -V --target-env vulkan1.0 --vn kTriangleFragSpv -o "$TMP/frag.h" "$SRC/triangle.frag"
# GLSL ES: syntax/semantic validation only.
"$GLSLANG" "$SRC/triangle_es.vert"
"$GLSLANG" "$SRC/triangle_es.frag"

{
  echo "// GENERATED by tools/compile_shaders.sh - do not edit by hand."
  echo "// Sources: shaders/triangle.{vert,frag} (Vulkan) and shaders/triangle_es.{vert,frag} (GLES)."
  echo "#pragma once"
  echo "#include <cstdint>"
  echo "namespace pe::shaders {"
  # glslang emits 'const uint32_t name[] = {...};'
  sed -e '/^[[:space:]]*\/\//d' -e '/#pragma once/d' -e 's/^const uint32_t/inline constexpr uint32_t/' "$TMP/vert.h"
  sed -e '/^[[:space:]]*\/\//d' -e '/#pragma once/d' -e 's/^const uint32_t/inline constexpr uint32_t/' "$TMP/frag.h"
  echo "inline constexpr const char* kTriangleVertEs = R\"GLSL($(cat "$SRC/triangle_es.vert"))GLSL\";"
  echo "inline constexpr const char* kTriangleFragEs = R\"GLSL($(cat "$SRC/triangle_es.frag"))GLSL\";"
  echo "}  // namespace pe::shaders"
} > "$OUT"
echo "Wrote $OUT"
