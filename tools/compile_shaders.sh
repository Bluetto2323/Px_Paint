#!/usr/bin/env bash
# Regenerates the embedded shader headers in app/src/main/cpp/shaders/generated/
#  - Vulkan GLSL 450  -> SPIR-V 1.0 (embedded as uint32_t arrays)
#  - GLSL ES 3.00     -> validated, embedded as source strings
#
# Usage: tools/compile_shaders.sh [path/to/glslangValidator]
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/app/src/main/cpp/shaders"
GLSLANG="${1:-${GLSLANG:-glslangValidator}}"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
command -v "$GLSLANG" >/dev/null 2>&1 || [ -x "$GLSLANG" ] || { echo "glslangValidator not found: $GLSLANG" >&2; exit 1; }

spv() {  # <source> <array name>
  "$GLSLANG" -V --target-env vulkan1.0 --vn "$2" -o "$TMP/$2.h" "$SRC/$1" >/dev/null
  sed -e '/^[[:space:]]*\/\//d' -e '/#pragma once/d' -e 's/^const uint32_t/inline constexpr uint32_t/' "$TMP/$2.h"
}
es() {   # <source> <constant name>
  "$GLSLANG" "$SRC/$1" >/dev/null
  echo "inline constexpr const char* $2 = R\"GLSL($(cat "$SRC/$1"))GLSL\";"
}
header() {  # <output> <description>
  echo "// GENERATED by tools/compile_shaders.sh - do not edit by hand."
  echo "// $2"
  echo "#pragma once"
  echo "#include <cstdint>"
  echo "namespace pe::shaders {"
}

{
  header x "Sources: shaders/triangle.{vert,frag} (Vulkan) and shaders/triangle_es.{vert,frag} (GLES)."
  spv triangle.vert kTriangleVertSpv
  spv triangle.frag kTriangleFragSpv
  es triangle_es.vert kTriangleVertEs
  es triangle_es.frag kTriangleFragEs
  echo "}  // namespace pe::shaders"
} > "$SRC/generated/TriangleShaders.h"

{
  header x "Sources: shaders/canvas*.{vert,frag} (Vulkan) and shaders/canvas*_es.{vert,frag} (GLES)."
  spv canvas.vert kCanvasVertSpv
  spv canvas_tex.frag kCanvasTexFragSpv
  spv canvas_solid.frag kCanvasSolidFragSpv
  es canvas_es.vert kCanvasVertEs
  es canvas_tex_es.frag kCanvasTexFragEs
  es canvas_solid_es.frag kCanvasSolidFragEs
  echo "}  // namespace pe::shaders"
} > "$SRC/generated/CanvasShaders.h"
echo "Wrote $SRC/generated/{TriangleShaders,CanvasShaders}.h"
