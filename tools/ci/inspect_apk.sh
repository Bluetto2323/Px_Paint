#!/usr/bin/env bash
# Inspects a built APK and FAILS if it does not match what the engine needs.
#   usage: tools/ci/inspect_apk.sh <app.apk>
# Requires ANDROID_HOME (build-tools 35) and ANDROID_NDK_HOME (llvm-readelf).
# Writes a human-readable summary to stdout (and to $GITHUB_STEP_SUMMARY in CI).
set -euo pipefail

APK="${1:?usage: inspect_apk.sh <app.apk>}"
BT="$ANDROID_HOME/build-tools/${BUILD_TOOLS_VERSION:-35.0.0}"
READELF="$ANDROID_NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64/bin/llvm-readelf"
EXPECTED_ABIS=(arm64-v8a x86_64)
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
# Expected JNI exports = native methods declared by the Kotlin facade.
JNI_EXPECTED=$(grep -c "private external fun native" "$ROOT/app/src/main/java/com/paintengine/engine/NativeEngine.kt")
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
fail=0
summary=()
note() { summary+=("$1"); echo "$1"; }
error() { summary+=("**ERROR** $1"); echo "ERROR: $1" >&2; fail=1; }

note "### APK: $(basename "$APK") ($(du -h "$APK" | cut -f1))"

# --- manifest / package -------------------------------------------------
badging="$("$BT/aapt2" dump badging "$APK")"
pkg=$(grep -oE "^package: name='[^']+'" <<<"$badging" | cut -d"'" -f2)
ver=$(grep -oE "versionName='[^']+'" <<<"$badging" | cut -d"'" -f2)
minsdk=$(grep -oE "^(sdkVersion|minSdkVersion):'[0-9]+'" <<<"$badging" | grep -oE "[0-9]+")
target=$(grep -oE "^targetSdkVersion:'[0-9]+'" <<<"$badging" | grep -oE "[0-9]+")
native=$(grep -oE "^native-code:.*" <<<"$badging" || true)
note "- package \`$pkg\` version \`$ver\`, minSdk $minsdk, targetSdk $target"
note "- $native"
[[ "$pkg" == "com.paintengine" ]] || error "unexpected package name '$pkg'"
grep -q "launchable-activity: name='com.paintengine.app.MainActivity'" <<<"$badging" ||
  error "launcher activity com.paintengine.app.MainActivity not found"
if grep -q "uses-feature-not-required: name='android.hardware.vulkan.version'" <<<"$badging" ||
   grep -q "uses-feature: name='android.hardware.vulkan.version'.*required='false'" <<<"$badging"; then
  note "- Vulkan declared as optional (devices without Vulkan can install the app)"
else
  error "android.hardware.vulkan.version must be declared required=false"
fi

# --- native libraries -----------------------------------------------------
unzip -q -o "$APK" 'lib/*' -d "$WORK"
for abi in "${EXPECTED_ABIS[@]}"; do
  so="$WORK/lib/$abi/libpaintengine.so"
  if [[ ! -f "$so" ]]; then error "lib/$abi/libpaintengine.so missing"; continue; fi
  size=$(du -h "$so" | cut -f1)
  needed=$("$READELF" -d "$so" | grep -oE "Shared library: \[[^]]+\]" | sed -E 's/.*\[(.*)\]/\1/' | tr '\n' ' ')
  # 16 KB page size compatibility: every PT_LOAD must be aligned to >= 0x4000.
  aligns=$("$READELF" -lW "$so" | awk '$1=="LOAD"{print $NF}' | sort -u | tr '\n' ' ')
  note "- \`lib/$abi/libpaintengine.so\` ($size) NEEDED: $needed| LOAD align: $aligns"
  for a in $aligns; do
    (( a >= 0x4000 )) || error "$abi: PT_LOAD alignment $a < 16 KB"
  done
  # Vulkan must be loaded with dlopen (fallback to GLES on devices without it).
  grep -qw "libvulkan.so" <<<"$needed" && error "$abi: libvulkan.so is linked directly (must be dlopen'ed)"
  for lib in libEGL.so libGLESv3.so libandroid.so liblog.so; do
    grep -qw "$lib" <<<"$needed" || error "$abi: expected dependency $lib missing"
  done
  # c++_static: no libc++_shared.so may be required.
  grep -qw "libc++_shared.so" <<<"$needed" && error "$abi: depends on libc++_shared.so (expected c++_static)"
  # Every JNI entry point declared in NativeEngine.kt must be exported.
  # (Symbols are read into a variable first: `readelf | grep -q` under
  # pipefail fails spuriously when grep exits early and readelf gets SIGPIPE.)
  dynsyms=$("$READELF" -W --dyn-syms "$so")
  jni=$(grep -c " Java_com_paintengine_engine_NativeEngine_" <<<"$dynsyms" || true)
  [[ "$jni" -eq "$JNI_EXPECTED" ]] || error "$abi: expected $JNI_EXPECTED exported JNI functions, found $jni"
  grep -qE " JNI_OnLoad(@@?[^ ]+)?$" <<<"$dynsyms" || error "$abi: JNI_OnLoad not exported"
  note "  - exports: $jni JNI functions + JNI_OnLoad"
done
extra=$(find "$WORK/lib" -mindepth 1 -maxdepth 1 -type d -printf '%f\n' | sort | tr '\n' ' ')
note "- ABIs in APK: $extra"

# --- zip alignment (uncompressed .so must be 16 KB aligned in the zip) -----
if "$BT/zipalign" -c -P 16 4 "$APK" > /dev/null; then
  note "- zipalign -P 16: OK (native libs page-aligned for 16 KB devices)"
else
  error "zipalign -c -P 16 4 failed"
fi

# --- signature (debug key generated by AGP on the CI runner) ---------------
if "$BT/apksigner" verify --print-certs "$APK" > "$WORK/sig.txt" 2>&1; then
  note "- signature: $(grep -m1 'certificate DN' "$WORK/sig.txt" | sed 's/^Signer #1 //')"
else
  error "apksigner verify failed: $(cat "$WORK/sig.txt")"
fi

if [[ -n "${GITHUB_STEP_SUMMARY:-}" ]]; then printf '%s\n' "${summary[@]}" >> "$GITHUB_STEP_SUMMARY"; fi
exit $fail
